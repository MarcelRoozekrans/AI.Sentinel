namespace AI.Sentinel.Transparency;

/// <summary>
/// Keys of the machine-readable AI-generated mark that <see cref="TransparencyOptions"/> adds to
/// <see cref="Microsoft.Extensions.AI.ChatResponse.AdditionalProperties"/>. A value the inner client already set is
/// kept, except for <see cref="Generated"/>. A streamed reply carries the mark on the first update without a message
/// id, which <c>ToChatResponse</c> merges into the response; when every update has a message id, on the first update,
/// which <c>ToChatResponse</c> merges into that update's message.
/// </summary>
public static class TransparencyKeys
{
    /// <summary><see langword="true"/>: the reply was generated by an AI system.</summary>
    public const string Generated = "ai.generated";

    /// <summary>The model that answered: <see cref="Microsoft.Extensions.AI.ChatResponse.ModelId"/>, else
    /// <see cref="Microsoft.Extensions.AI.ChatOptions.ModelId"/>. Absent when neither is known.</summary>
    public const string ModelId = "ai.model_id";

    /// <summary>When the reply was marked, as an ISO 8601 UTC timestamp string.</summary>
    public const string GeneratedAt = "ai.generated_at";

    /// <summary>The name of the named AI.Sentinel pipeline that marked the reply. Absent for the default pipeline.</summary>
    public const string Pipeline = "ai.pipeline";
}
