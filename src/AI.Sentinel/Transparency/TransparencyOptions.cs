namespace AI.Sentinel.Transparency;

/// <summary>Opt-in EU AI Act Art. 50 transparency settings: a machine-readable AI-generated mark on
/// replies and an optional human-readable notice. Off by default.</summary>
public sealed class TransparencyOptions
{
    /// <summary>Turns transparency on. Defaults to <see langword="false"/>, so existing behaviour is unchanged.</summary>
    public bool Enabled { get; set; }

    /// <summary>Text of the human-readable notice. Must not be empty unless <see cref="NoticeMode"/> is
    /// <see cref="TransparencyNoticeMode.Never"/>.</summary>
    public string Notice { get; set; } = "This answer was generated by AI.";

    /// <summary>When the notice is added to a reply. Defaults to <see cref="TransparencyNoticeMode.OncePerConversation"/>.</summary>
    public TransparencyNoticeMode NoticeMode { get; set; } = TransparencyNoticeMode.OncePerConversation;
}
