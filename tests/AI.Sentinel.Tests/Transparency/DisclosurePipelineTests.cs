    /// <summary>Records every message it is asked to judge; flags assistant text containing "FORBIDDEN".</summary>
    private sealed class RecordingDetector : IDetector
    {
        public List<string> Seen { get; } = [];

        public DetectorId Id { get; } = new("TEST-REC");

        public DetectorCategory Category => DetectorCategory.Operational;

        public ValueTask<DetectionResult> AnalyzeAsync(SentinelContext ctx, CancellationToken ct)
        {
            lock (Seen)
            {
                foreach (var m in ctx.Messages)
                {
                    Seen.Add(m.Text);
                }
            }
            var forbidden = ctx.Messages.Any(m => m.Role == ChatRole.Assistant && m.Text.Contains("FORBIDDEN", StringComparison.Ordinal));
            return ValueTask.FromResult(forbidden
                ? DetectionResult.WithSeverity(Id, Severity.Critical, "forbidden reply")
                : DetectionResult.Clean(Id));
        }
    }

    /// <summary>An audit store whose first DISCLOSED append throws.</summary>
    private sealed class ThrowsOnFirstDisclosedStore : IAuditStore
    {
        private int _thrown;

        public RingBufferAuditStore Inner { get; } = new(100);

        public ValueTask<AuditEntry> AppendAsync(AuditEntry entry, CancellationToken ct)
        {
            if (string.Equals(entry.PolicyCode, AuditEntryKinds.DisclosedPolicyCode, StringComparison.Ordinal)
                && Interlocked.Exchange(ref _thrown, 1) == 0)
            {
                throw new InvalidOperationException("audit store unavailable");
            }
            return Inner.AppendAsync(entry, ct);
        }

        public IAsyncEnumerable<AuditEntry> QueryAsync(AuditQuery query, CancellationToken ct) => Inner.QueryAsync(query, ct);
    }

    /// <summary>Redacts every "SECRET" and finds nothing to flag.</summary>
    private sealed class SecretRedactor : IRedactingDetector
    {
        public DetectorId Id { get; } = new("TEST-SECRET");

        public DetectorCategory Category => DetectorCategory.Security;

        public ValueTask<DetectionResult> AnalyzeAsync(SentinelContext ctx, CancellationToken ct) =>
            ValueTask.FromResult(DetectionResult.Clean(Id));

        public IReadOnlyList<RedactionSpan> FindSpans(string text)
        {
            var spans = new List<RedactionSpan>();
            for (var i = text.IndexOf("SECRET", StringComparison.Ordinal); i >= 0; i = text.IndexOf("SECRET", i + 6, StringComparison.Ordinal))
            {
                spans.Add(new RedactionSpan(i, 6, "SECRET"));
            }
            return spans;
        }
    }

    private sealed record Harness(SentinelPipeline Pipeline, FakeModel Model, RingBufferAuditStore Audit, RecordingDetector Detector, ManualClock Clock);

    private static readonly DateTimeOffset Start = new(2026, 10, 17, 12, 0, 0, TimeSpan.Zero);

    private static Harness Build(FakeModel model, Action<SentinelOptions>? configure = null, IChatClient? inner = null, bool enabled = true)
    {
        var opts = new SentinelOptions();
        opts.Transparency.Enabled = enabled;
        configure?.Invoke(opts);
        var audit = new RingBufferAuditStore(100);
        var detector = new RecordingDetector();
        var clock = new ManualClock(Start);
        var pipeline = new SentinelPipeline(inner ?? model, new DetectionPipeline([detector], null, null), audit,
            new InterventionEngine(opts, null), opts, pipelineName: null, timeProvider: clock);
        return new Harness(pipeline, model, audit, detector, clock);
    }

    private static ChatOptions Session(string id, string? modelId = null) => new()
    {
        ModelId = modelId,
        AdditionalProperties = new AdditionalPropertiesDictionary { [SentinelPipeline.SessionIdKey] = id },
    };

    private static async Task<ChatResponse> AskAsync(Harness h, ChatOptions? options, params ChatMessage[] messages)
    {
        var result = await h.Pipeline.GetResponseResultAsync(
            messages.Length == 0 ? [new ChatMessage(ChatRole.User, "Hello there")] : messages,
            options, TestContext.Current.CancellationToken);
        Assert.True(result.IsSuccess, result.IsFailure ? result.Error.ToString() : null);
        return result.Value;
    }

    private static async Task<List<AuditEntry>> DisclosedAsync(IAuditStore audit) =>
        (await RecordingAuditForwarder.ReadAllAsync(audit))
            .Where(e => string.Equals(e.PolicyCode, AuditEntryKinds.DisclosedPolicyCode, StringComparison.Ordinal))
            .ToList();

    private static bool HasNotice(ChatMessage message) =>
        message.Contents.Count > 0 && message.Contents[0] is TextContent { Text: NoticeText };

    private static int NoticeCount(ChatResponse response) => response.Messages.Count(HasNotice);

