    [Fact]
    public async Task Streaming_UpdateCountAndMetadataOtherwiseUnchanged()
    {
        var created = new DateTimeOffset(2026, 10, 17, 11, 0, 0, TimeSpan.Zero);
        var raw = new object();
        var h = Build(new StreamModel(_ =>
        [
            new ChatResponseUpdate(ChatRole.Assistant, "Hel")
            {
                MessageId = "m1", ResponseId = "r1", CreatedAt = created, RawRepresentation = raw,
                AdditionalProperties = new AdditionalPropertiesDictionary { ["other"] = 42 },
            },
            new ChatResponseUpdate(null, "lo.") { MessageId = "m1", ResponseId = "r1", FinishReason = ChatFinishReason.Stop },
            new ChatResponseUpdate(null, [new UsageContent(new UsageDetails { TotalTokenCount = 7 })]) { ResponseId = "r1" },
        ]));

        var updates = await StreamAsync(h, Session("s1"));
        var inner = h.Model.LastUpdates!;

        Assert.Equal(inner.Count, updates.Count);
        for (var i = 0; i < inner.Count; i++)
        {
            Assert.Equal(inner[i].MessageId, updates[i].MessageId);
            Assert.Equal(inner[i].ResponseId, updates[i].ResponseId);
            Assert.Equal(inner[i].Role, updates[i].Role);
            Assert.Equal(inner[i].CreatedAt, updates[i].CreatedAt);
            Assert.Equal(inner[i].FinishReason, updates[i].FinishReason);
            Assert.Same(inner[i].RawRepresentation, updates[i].RawRepresentation);
            Assert.Equal(inner[i].Contents, WithoutNotice(updates[i]));
        }
        // The mark is on the usage update, the one without a message id; the others keep their properties.
        Assert.Equal(new AdditionalPropertiesDictionary { ["other"] = 42 }, updates[0].AdditionalProperties);
        Assert.Null(updates[1].AdditionalProperties);
        Assert.True(updates[2].AdditionalProperties![TransparencyKeys.Generated] is true);
        Assert.Equal(NoticeText + "Hello.", TextOf(updates));

        // The inner client's updates are not mutated.
        Assert.Null(inner[2].AdditionalProperties);
        Assert.Equal("Hel", inner[0].Text);
        Assert.Single(inner[0].Contents);
    }

    [Fact]
    public async Task Streaming_FunctionInvocationInside_WithSessionKey_OneNoticeOneEntry_HistoryStripped()
    {
        var calls = 0;
        var model = new StreamModel(_ => ++calls == 1
            ? [new ChatResponseUpdate(ChatRole.Assistant, "Let me check."), new ChatResponseUpdate(null, [new FunctionCallContent("c1", "Lookup")])]
            : Chunks("It is ", "sunny."));
        var audit = new RingBufferAuditStore(100);
        var services = new ServiceCollection();
        services.AddAISentinel(o => o.Transparency.Enabled = true);
        services.AddSingleton<IAuditStore>(audit);
        using var client = new ChatClientBuilder(model).UseFunctionInvocation().UseAISentinel().Build(services.BuildServiceProvider());
        var options = Session("s1");
        options.Tools = [AIFunctionFactory.Create(() => "sunny", "Lookup")];

        var updates = new List<ChatResponseUpdate>();
        await foreach (var update in client.GetStreamingResponseAsync([new ChatMessage(ChatRole.User, "Weather?")], options, TestContext.Current.CancellationToken))
            updates.Add(update);

        Assert.Equal(1, NoticeCount(updates));
        var noticed = Assert.Single(updates, u => u.Contents.Any(IsNotice));
        Assert.Equal(NoticeText + "Let me check.", noticed.Text);
        Assert.Equal(NoticeText + "Let me check.It is sunny.", TextOf(updates));
        var entry = Assert.Single(await DisclosedAsync(audit));
        Assert.Equal("s1", entry.SessionId);

        Assert.Equal(2, model.Received.Count);
        var earlier = Assert.Single(model.Received[1], m => m.Role == ChatRole.Assistant);
        Assert.Equal("Let me check.", earlier.Text);
        Assert.DoesNotContain(model.Received[1], m => m.Text.Contains(Notice, StringComparison.Ordinal));
    }

    [Fact]
    public async Task Streaming_HistoryNoticeStripped()
    {
        var h = Build(StreamModel.Text("Hi ", "there."), o => o.Transparency.NoticeMode = TransparencyNoticeMode.EveryReply);
        List<ChatMessage> history = [new ChatMessage(ChatRole.User, "Hello")];
        var first = await StreamAsync(h, Session("s1"), [.. history]);

        // The way an app keeps a streamed reply: the updates folded into messages, which joins adjacent text.
        history.AddMessages(first);
        Assert.StartsWith(NoticeText, history[^1].Text, StringComparison.Ordinal);
        var kept = history[^1];
        history.Add(new ChatMessage(ChatRole.User, "And now?"));
        var second = await StreamAsync(h, Session("s1"), [.. history]);

        var sent = h.Model.Received[^1];
        Assert.Equal(3, sent.Count);
        Assert.Equal("Hi there.", sent[1].Text);
        Assert.DoesNotContain(h.Detector.Seen, s => s.Contains(Notice, StringComparison.Ordinal));
        Assert.StartsWith(NoticeText, kept.Text, StringComparison.Ordinal);
        Assert.Equal(1, NoticeCount(second));
    }

    [Fact]
    public async Task Streaming_HistoryNoticeAfterReasoning_StrippedFromJoinedText()
    {
        var h = Build(StreamModel.Text("Fine."));
        var previous = new ChatMessage(ChatRole.Assistant,
        [
            new TextReasoningContent("thinking"),
            new TextContent(NoticeText + "It is sunny.") { AdditionalProperties = new AdditionalPropertiesDictionary { ["x"] = 1 } },
        ]);

        await StreamAsync(h, Session("s1"), new ChatMessage(ChatRole.User, "Weather?"), previous, new ChatMessage(ChatRole.User, "Thanks"));

        var sent = h.Model.Received[^1][1];
        Assert.IsType<TextReasoningContent>(sent.Contents[0]);
        var text = Assert.IsType<TextContent>(sent.Contents[1]);
        Assert.Equal("It is sunny.", text.Text);
        Assert.Equal(1, text.AdditionalProperties!["x"]);
        Assert.Equal(NoticeText + "It is sunny.", previous.Text);
    }

