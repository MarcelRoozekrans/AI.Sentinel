    [Fact]
    public async Task Streaming_NoticeBeforeFirstText_Once()
    {
        // An intermediate assistant message with text and a tool call, the tool's result, then the final answer:
        // the notice goes on the final assistant text, in the first update that carries its text.
        var h = Build(new StreamModel(_ =>
        [
            new ChatResponseUpdate(ChatRole.Assistant, [new TextContent("Let me check."), new FunctionCallContent("c1", "Lookup")]) { MessageId = "m1" },
            new ChatResponseUpdate(ChatRole.Tool, [new FunctionResultContent("c1", "sunny")]) { MessageId = "m2" },
            new ChatResponseUpdate(ChatRole.Assistant, [new TextReasoningContent("thinking")]) { MessageId = "m3" },
            new ChatResponseUpdate(null, "It is ") { MessageId = "m3" },
            new ChatResponseUpdate(null, "sunny.") { MessageId = "m3" },
        ]));

        var first = await StreamAsync(h, Session("s1"));
        var second = await StreamAsync(h, Session("s1"));

        Assert.Equal(1, NoticeCount(first));
        Assert.True(IsNotice(first[3].Contents[0]));
        Assert.Equal(NoticeText + "It is ", first[3].Text);
        var messages = first.ToChatResponse().Messages;
        Assert.Equal("Let me check.", messages[0].Text);
        Assert.Equal(NoticeText + "It is sunny.", messages[^1].Text);
        Assert.Equal(0, NoticeCount(second));
        Assert.Equal(true, second[0].AdditionalProperties![TransparencyKeys.Generated]);
        var entry = Assert.Single(await DisclosedAsync(h.Audit));
        Assert.Equal("s1", entry.SessionId);
        Assert.Equal("Disclosed: machine-readable mark and notice", entry.Summary);
    }

