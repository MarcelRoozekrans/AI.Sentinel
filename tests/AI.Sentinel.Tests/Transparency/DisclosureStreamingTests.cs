// Art. 50 on the streaming path: the mark rides on the first update without a MessageId, whose properties
// ToChatResponse merges into the response, else on the first update; the notice is a leading text in the first
// text update of the last assistant message with text.
public class DisclosureStreamingTests
{
    private const string Notice = "This answer was generated by AI.";
    private const string NoticeText = Notice + "\n\n";

    private static readonly DateTimeOffset Start = new(2026, 10, 17, 12, 0, 0, TimeSpan.Zero);

    private sealed class ManualClock(DateTimeOffset start) : TimeProvider
    {
        public DateTimeOffset Now { get; set; } = start;

        public override DateTimeOffset GetUtcNow() => Now;
    }

    /// <summary>A model that streams scripted updates, built fresh per call, and records what it was sent.</summary>
    private sealed class StreamModel(Func<IReadOnlyList<ChatMessage>, List<ChatResponseUpdate>> answer) : IChatClient
    {
        public List<List<ChatMessage>> Received { get; } = [];

        public List<ChatResponseUpdate>? LastUpdates { get; private set; }

        public static StreamModel Text(params string[] chunks) => new(_ => Chunks(chunks));

        public Task<ChatResponse> GetResponseAsync(IEnumerable<ChatMessage> messages, ChatOptions? options = null, CancellationToken cancellationToken = default)
            => throw new NotSupportedException();

        public async IAsyncEnumerable<ChatResponseUpdate> GetStreamingResponseAsync(IEnumerable<ChatMessage> messages, ChatOptions? options = null, [EnumeratorCancellation] CancellationToken cancellationToken = default)
        {
            var list = messages.ToList();
            Received.Add(list);
            LastUpdates = answer(list);
            foreach (var update in LastUpdates)
            {
                await Task.Yield();
                yield return update;
            }
        }

        public object? GetService(Type serviceType, object? serviceKey = null) => null;

        public void Dispose() { }
    }

    /// <summary>Records every message it judges; flags assistant text containing "FORBIDDEN".</summary>
    private sealed class RecordingDetector : IDetector
    {
        public List<string> Seen { get; } = [];

        public DetectorId Id { get; } = new("TEST-REC");

        public DetectorCategory Category => DetectorCategory.Operational;

        public ValueTask<DetectionResult> AnalyzeAsync(SentinelContext ctx, CancellationToken ct)
        {
            lock (Seen)
            {
                foreach (var m in ctx.Messages)
                {
                    Seen.Add(m.Text);
                }
            }
            var forbidden = ctx.Messages.Any(m => m.Role == ChatRole.Assistant && m.Text.Contains("FORBIDDEN", StringComparison.Ordinal));
            return ValueTask.FromResult(forbidden
                ? DetectionResult.WithSeverity(Id, Severity.Critical, "forbidden reply")
                : DetectionResult.Clean(Id));
        }
    }

    /// <summary>Redacts every "SECRET" and finds nothing to flag.</summary>
    private sealed class SecretRedactor : IRedactingDetector
    {
        public DetectorId Id { get; } = new("TEST-SECRET");

        public DetectorCategory Category => DetectorCategory.Security;

        public ValueTask<DetectionResult> AnalyzeAsync(SentinelContext ctx, CancellationToken ct) =>
            ValueTask.FromResult(DetectionResult.Clean(Id));

        public IReadOnlyList<RedactionSpan> FindSpans(string text)
        {
            var spans = new List<RedactionSpan>();
            for (var i = text.IndexOf("SECRET", StringComparison.Ordinal); i >= 0; i = text.IndexOf("SECRET", i + 6, StringComparison.Ordinal))
            {
                spans.Add(new RedactionSpan(i, 6, "SECRET"));
            }
            return spans;
        }
    }

    /// <summary>An audit store whose first DISCLOSED append throws.</summary>
    private sealed class ThrowsOnFirstDisclosedStore : IAuditStore
    {
        private int _thrown;

        public RingBufferAuditStore Inner { get; } = new(100);

        public ValueTask<AuditEntry> AppendAsync(AuditEntry entry, CancellationToken ct)
        {
            if (string.Equals(entry.PolicyCode, AuditEntryKinds.DisclosedPolicyCode, StringComparison.Ordinal)
                && Interlocked.Exchange(ref _thrown, 1) == 0)
            {
                throw new InvalidOperationException("audit store unavailable");
            }
            return Inner.AppendAsync(entry, ct);
        }

        public IAsyncEnumerable<AuditEntry> QueryAsync(AuditQuery query, CancellationToken ct) => Inner.QueryAsync(query, ct);
    }

    private sealed record Harness(SentinelPipeline Pipeline, StreamModel Model, IAuditStore Audit, RecordingDetector Detector);

    private static Harness Build(
        StreamModel model,
        Action<SentinelOptions>? configure = null,
        IAuditStore? audit = null,
        IDetector? extra = null,
        string? pipelineName = null)
    {
        var opts = new SentinelOptions();
        opts.Transparency.Enabled = true;
        configure?.Invoke(opts);
        audit ??= new RingBufferAuditStore(100);
        var detector = new RecordingDetector();
        IDetector[] detectors = extra is null ? [detector] : [detector, extra];
        var pipeline = new SentinelPipeline(model, new DetectionPipeline(detectors, null, null), audit,
            new InterventionEngine(opts, null), opts, pipelineName: pipelineName, timeProvider: new ManualClock(Start));
        return new Harness(pipeline, model, audit, detector);
    }

    private static List<ChatResponseUpdate> Chunks(params string[] chunks)
    {
        var updates = new List<ChatResponseUpdate>();
        for (var i = 0; i < chunks.Length; i++)
        {
            updates.Add(new ChatResponseUpdate(i == 0 ? ChatRole.Assistant : null, chunks[i]));
        }
        return updates;
    }

    private static ChatOptions Session(string id, string? modelId = null) => new()
    {
        ModelId = modelId,
        AdditionalProperties = new AdditionalPropertiesDictionary { [SentinelPipeline.SessionIdKey] = id },
    };

    private static async Task<Result<IReadOnlyList<ChatResponseUpdate>, SentinelError>> TryStreamAsync(
        Harness h, ChatOptions? options, params ChatMessage[] messages) =>
        await h.Pipeline.GetStreamingResultAsync(
            messages.Length == 0 ? [new ChatMessage(ChatRole.User, "Hello there")] : messages,
            options, TestContext.Current.CancellationToken);

    private static async Task<IReadOnlyList<ChatResponseUpdate>> StreamAsync(Harness h, ChatOptions? options, params ChatMessage[] messages)
    {
        var result = await TryStreamAsync(h, options, messages);
        Assert.True(result.IsSuccess, result.IsFailure ? result.Error.ToString() : null);
        return result.Value;
    }

    private static async Task<List<AuditEntry>> DisclosedAsync(IAuditStore audit) =>
        (await RecordingAuditForwarder.ReadAllAsync(audit))
            .Where(e => string.Equals(e.PolicyCode, AuditEntryKinds.DisclosedPolicyCode, StringComparison.Ordinal))
            .ToList();

    private static bool IsNotice(AIContent content) => content is TextContent { Text: NoticeText };

    private static int NoticeCount(IReadOnlyList<ChatResponseUpdate> updates) =>
        updates.Sum(u => u.Contents.Count(IsNotice));

    private static List<AIContent> WithoutNotice(ChatResponseUpdate update) => update.Contents.Where(c => !IsNotice(c)).ToList();

    private static string TextOf(IReadOnlyList<ChatResponseUpdate> updates) => string.Concat(updates.Select(u => u.Text));

    [Fact]
    public async Task Streaming_MarkSurvivesToChatResponse()
    {
        var answered = Build(new StreamModel(_ =>
        {
            var updates = Chunks("Hel", "lo.");
            updates[^1].ModelId = "answered-model";
            return updates;
        }), pipelineName: "support");
        var fallback = Build(StreamModel.Text("Hel", "lo."));

        var a = await StreamAsync(answered, Session("s1", modelId: "requested-model"));
        var b = await StreamAsync(fallback, Session("s1", modelId: "requested-model"));

        Assert.True(a[0].AdditionalProperties![TransparencyKeys.Generated] is true);
        var props = a.ToChatResponse().AdditionalProperties!;
        Assert.True(props[TransparencyKeys.Generated] is true);
        Assert.Equal("answered-model", props[TransparencyKeys.ModelId]);
        Assert.Equal("2026-10-17T12:00:00.0000000Z", props[TransparencyKeys.GeneratedAt]);
        Assert.Equal("support", props[TransparencyKeys.Pipeline]);

        var fallbackProps = b.ToChatResponse().AdditionalProperties!;
        Assert.True(fallbackProps[TransparencyKeys.Generated] is true);
        Assert.Equal("requested-model", fallbackProps[TransparencyKeys.ModelId]);
        Assert.False(fallbackProps.ContainsKey(TransparencyKeys.Pipeline));
    }

    [Fact]
    public async Task Streaming_MarkOnUpdateThatReachesTheResponse()
    {
        // ToChatResponse scopes the properties of an update with a message id to its message; only an update
        // without one reaches the response, so that is where the mark goes.
        var h = Build(new StreamModel(_ =>
        [
            new ChatResponseUpdate(ChatRole.Assistant, "Hi.") { MessageId = "m1" },
            new ChatResponseUpdate(null, [new UsageContent(new UsageDetails { TotalTokenCount = 3 })]),
        ]));

        var updates = await StreamAsync(h, Session("s1"));

        Assert.Null(updates[0].AdditionalProperties);
        Assert.True(updates[1].AdditionalProperties![TransparencyKeys.Generated] is true);
        Assert.True(updates.ToChatResponse().AdditionalProperties![TransparencyKeys.Generated] is true);
    }

