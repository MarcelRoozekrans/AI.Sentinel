    [Fact]
    public async Task Streaming_RestoreFails_NoMarkNoNoticeNoEntry()
    {
        // Restoring the tool argument makes its two keys identical, so the restore fails.
        var h = Build(new StreamModel(sent =>
        {
            var placeholder = Regex.Match(sent[^1].Text, @"\[SECRET_[^\]]+\]", RegexOptions.None, TimeSpan.FromSeconds(1)).Value;
            Assert.NotEmpty(placeholder);
            var payload = new Dictionary<string, object?>(StringComparer.Ordinal) { [placeholder] = "a", ["SECRET"] = "b" };
            return
            [
                new ChatResponseUpdate(ChatRole.Assistant, [new TextContent("Hi."), new FunctionCallContent("c1", "Send",
                    new Dictionary<string, object?>(StringComparer.Ordinal) { ["payload"] = payload })]) { MessageId = "m1" },
            ];
        }), extra: new SecretRedactor());

        var result = await TryStreamAsync(h, Session("s1"), new ChatMessage(ChatRole.User, "my SECRET"));

        Assert.True(result.IsFailure);
        Assert.IsType<SentinelError.PipelineFailure>(result.Error);
        Assert.Null(h.Model.LastUpdates![0].AdditionalProperties?.GetValueOrDefault(TransparencyKeys.Generated));
        Assert.Empty(await DisclosedAsync(h.Audit));
        Assert.Equal(0, h.Pipeline.Disclosure.TrackedSessions);
    }

    [Fact]
    public async Task Streaming_AuditAppendFails_ClaimRolledBack_NextReplyStillDisclosed()
    {
        var audit = new ThrowsOnFirstDisclosedStore();
