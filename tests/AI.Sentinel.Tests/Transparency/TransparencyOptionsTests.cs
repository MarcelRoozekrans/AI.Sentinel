using Microsoft.Extensions.DependencyInjection;
using AI.Sentinel.Transparency;
using Xunit;

namespace AI.Sentinel.Tests.Transparency;

public class TransparencyOptionsTests
{
    [Fact]
    public void Defaults_AreOffOncePerConversationWithDefaultNotice()
    {
        var t = new SentinelOptions().Transparency;

        Assert.False(t.Enabled);
        Assert.Equal("This answer was generated by AI.", t.Notice);
        Assert.Equal(TransparencyNoticeMode.OncePerConversation, t.NoticeMode);
    }

    [Theory]
    [InlineData("")]
    [InlineData("   ")]
    public void EnabledWithEmptyNotice_AndModeNotNever_ThrowsOnAddAISentinel(string notice)
    {
        var services = new ServiceCollection();

        var ex = Assert.Throws<ArgumentException>(() => services.AddAISentinel(o =>
        {
            o.Transparency.Enabled = true;
            o.Transparency.Notice = notice;
        }));

        Assert.Contains("Transparency.Notice", ex.Message, StringComparison.Ordinal);
    }

    [Fact]
    public void EnabledWithEmptyNotice_ModeNever_IsAllowed()
    {
        var services = new ServiceCollection();

        var ex = Record.Exception(() => services.AddAISentinel(o =>
        {
            o.Transparency.Enabled = true;
            o.Transparency.Notice = "";
            o.Transparency.NoticeMode = TransparencyNoticeMode.Never;
        }));

        Assert.Null(ex);
    }

    [Fact]
    public void EnabledWithEmptyNotice_ModeEveryReply_Throws()
    {
        var services = new ServiceCollection();

        var ex = Assert.Throws<ArgumentException>(() => services.AddAISentinel(o =>
        {
            o.Transparency.Enabled = true;
            o.Transparency.Notice = "";
            o.Transparency.NoticeMode = TransparencyNoticeMode.EveryReply;
        }));

        Assert.Contains("Transparency.Notice", ex.Message, StringComparison.Ordinal);
    }

    [Fact]
    public void NamedPipeline_EnabledWithEmptyNotice_Throws()
    {
        var services = new ServiceCollection();

        var ex = Assert.Throws<ArgumentException>(() => services.AddAISentinel("named", o =>
        {
            o.Transparency.Enabled = true;
            o.Transparency.Notice = "";
        }));

        Assert.Contains("Transparency.Notice", ex.Message, StringComparison.Ordinal);
    }

    [Fact]
    public void Enabled_UndefinedNoticeMode_Throws()
    {
        var services = new ServiceCollection();

        var ex = Assert.Throws<ArgumentException>(() => services.AddAISentinel(o =>
        {
            o.Transparency.Enabled = true;
            o.Transparency.NoticeMode = (TransparencyNoticeMode)3;
        }));

        Assert.Contains("Transparency.NoticeMode", ex.Message, StringComparison.Ordinal);
    }

    [Fact]
    public void NamedPipeline_Enabled_UndefinedNoticeMode_Throws()
    {
        var services = new ServiceCollection();

        var ex = Assert.Throws<ArgumentException>(() => services.AddAISentinel("named", o =>
        {
            o.Transparency.Enabled = true;
            o.Transparency.NoticeMode = (TransparencyNoticeMode)3;
        }));

        Assert.Contains("Transparency.NoticeMode", ex.Message, StringComparison.Ordinal);
    }

    [Fact]
    public void Disabled_UndefinedNoticeMode_IsAllowed()
    {
        var services = new ServiceCollection();

        var ex = Record.Exception(() => services.AddAISentinel(o => o.Transparency.NoticeMode = (TransparencyNoticeMode)3));

        Assert.Null(ex);
    }
}
